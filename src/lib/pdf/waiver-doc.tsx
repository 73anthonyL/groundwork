import React from "react";
import { Document, Font, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import { WAIVER_TITLES, waiverBody, type WaiverFields, type WaiverFormId } from "@/domain/waivers/ca";

Font.registerHyphenationCallback((w) => [w]);

const s = StyleSheet.create({
  page: { paddingTop: 60, paddingBottom: 60, paddingHorizontal: 64, fontFamily: "Helvetica", fontSize: 10, lineHeight: 1.45 },
  title: { fontFamily: "Helvetica-Bold", fontSize: 13, textAlign: "center" },
  cite: { textAlign: "center", color: "#444", marginBottom: 12 },
  notice: { fontFamily: "Helvetica-Bold", fontSize: 9, marginBottom: 10, lineHeight: 1.4 },
  h: { fontFamily: "Helvetica-Bold", marginTop: 8, marginBottom: 2 },
  p: { marginBottom: 6 },
  sig: { marginTop: 24, borderTopWidth: 0.5, borderColor: "#333", paddingTop: 8 },
  mono: { fontFamily: "Courier", fontSize: 8, color: "#444" },
  footer: { position: "absolute", bottom: 30, left: 64, right: 64, fontSize: 7, color: "#666", textAlign: "center" },
});

export function WaiverDocument({
  fields,
  signature,
}: {
  fields: WaiverFields;
  signature: { signerName: string; signerTitle: string | null; signedAt: Date; hash: string } | null;
}) {
  const meta = WAIVER_TITLES[fields.form as WaiverFormId];
  const lines = waiverBody(fields).slice(2); // title + cite rendered separately
  return (
    <Document title={meta.title} author="Groundwork">
      <Page size="LETTER" style={s.page}>
        <Text style={s.title}>{meta.title.toUpperCase()}</Text>
        <Text style={s.cite}>(California {meta.cite})</Text>
        {lines.map((line, i) => {
          if (line === "") return <View key={i} style={{ height: 4 }} />;
          if (/^NOTICE/.test(line)) return <Text key={i} style={s.notice}>{line}</Text>;
          if (line === "Identifying Information" || line === "Exceptions") return <Text key={i} style={s.h}>{line}</Text>;
          return <Text key={i} style={s.p}>{line}</Text>;
        })}
        <View style={s.sig}>
          <Text style={s.h}>Signature</Text>
          {signature ? (
            <>
              <Text>Claimant&apos;s Signature: /s/ {signature.signerName}</Text>
              <Text>Claimant&apos;s Title: {signature.signerTitle ?? ""}</Text>
              <Text>Date of Signature: {signature.signedAt.toISOString().slice(0, 10)}</Text>
              <Text style={[s.mono, { marginTop: 6 }]}>Electronic signature. sha256 {signature.hash}</Text>
              <Text style={s.mono}>Binds the waiver id, every field above, the signer name and the signing time. Verify in Groundwork.</Text>
            </>
          ) : (
            <>
              <Text>Claimant&apos;s Signature: ______________________________</Text>
              <Text>Claimant&apos;s Title: ______________________________</Text>
              <Text>Date of Signature: ______________________________</Text>
            </>
          )}
        </View>
        <Text style={s.footer} fixed>
          Generated by Groundwork from the statutory form. Demo document; fictional parties.
        </Text>
      </Page>
    </Document>
  );
}
