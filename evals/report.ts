/**
 * Renders evals/results/REPORT.md from a results file: breakdowns the run summary (latest.md) does
 * not have (per field, per field group, by model confidence, presence and timing-type confusion
 * tables, every miss with its error type) and the regression gate's verdict.
 *
 * Pure and deterministic: the same results file, thresholds and cache records give the same bytes,
 * so the report is committed and a change to it shows up in review. scripts/eval-report.ts is the
 * command-line wrapper (`pnpm eval:report`).
 */
import { RULE_FIELDS } from "../src/domain/rules/schema";
import { evaluateGate, type Thresholds } from "./gate";
import type { RunFile } from "./run-file";
import { bootstrap, LAYER_LABEL, LAYERS, metrics, type ContractResult, type FieldResult, type Metrics } from "./score";

/** What the cache record of one scored contract says about how it was extracted. */
export type Extraction = { slug: string; model: string; promptVersion: string | null; ms: number; inputTokens: number | null; outputTokens: number | null; at: string | null };

export type MissKind = "wrong value" | "spurious value" | "missed value";

type Miss = FieldResult & { slug: string; category: string; kind: MissKind };

/** timing.type "silent" and a not-found field say the same thing, as in score.ts. */
const absent = (f: FieldResult, v: unknown) => v === null || v === undefined || (f.path === "timing.type" && v === "silent");

export function missKind(f: FieldResult): MissKind {
  if (absent(f, f.expected)) return "spurious value";
  if (absent(f, f.actual)) return "missed value";
  return "wrong value";
}

const pct = (x: number | null, digits = 1) => (x === null ? "n/a" : `${(100 * x).toFixed(digits)}%`);
const frac = (a: number, b: number) => (b ? `${a}/${b} (${pct(a / b)})` : "0/0 (n/a)");
const ci = (c: [number, number] | null) => (c ? `${(100 * c[0]).toFixed(1)}–${(100 * c[1]).toFixed(1)}%` : "n/a");
/** Markdown table cell: JSON for values, pipes escaped so a value cannot break the row. */
const cell = (v: unknown) => (v === undefined ? "null" : JSON.stringify(v)).replace(/\|/g, "\\|");
const table = (head: string[], rows: (string | number)[][]) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)];
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : null;
};
const groupOf = (path: string) => (path.includes(".") ? path.split(".")[0] : "top-level (governing law, stored materials)");

function tally(fields: FieldResult[]) {
  const wrong = fields.filter((f) => !f.correct);
  return { n: fields.length, correct: fields.length - wrong.length, wrong: wrong.length, flagged: fields.filter((f) => f.flagged.L3).length, silent: wrong.filter((f) => !f.flagged.L3).length };
}

export function renderReport(run: RunFile, opts: { thresholds?: Thresholds; extractions?: Extraction[]; source?: string } = {}): string {
  const results: ContractResult[] = run.results;
  const m = metrics(results);
  const all = results.flatMap((r) => r.fields.map((f) => ({ ...f, slug: r.slug, category: r.category })));
  const misses: Miss[] = all.filter((f) => !f.correct).map((f) => ({ ...f, kind: missKind(f) }));
  const quoted = all.filter((f) => f.quoted);
  const categories = [...new Set(results.map((r) => r.category))].sort();
  const L: string[] = [];

  L.push("# Extraction eval report", "");
  L.push(`Generated by \`pnpm eval:report\` from \`${opts.source ?? "evals/results/latest.json"}\`. Do not edit by hand: change the inputs and regenerate. Definitions of every metric are in [evals/README.md](../README.md#metrics).`, "");

  // ── Run ───────────────────────────────────────────────────────────────
  L.push("## Run", "");
  const ex = (opts.extractions ?? []).filter((e) => results.some((r) => r.slug === e.slug));
  const runRows: (string | number)[][] = [
    ["Results written", `\`${run.at}\``],
    ["Contracts", `${m.contracts} (${categories.map((c) => `${results.filter((r) => r.category === c).length} ${c}`).join(", ")})`],
    ["Fields", `${m.fields} (${RULE_FIELDS.length} per contract)`],
  ];
  if (ex.length) {
    const times = ex.map((e) => e.at).filter((t): t is string => !!t).sort();
    const tokIn = ex.reduce((s, e) => s + (e.inputTokens ?? 0), 0);
    const tokOut = ex.reduce((s, e) => s + (e.outputTokens ?? 0), 0);
    const med = median(ex.map((e) => e.ms));
    runRows.push(
      ["Extractions with a cache record", `${ex.length} of ${m.contracts}`],
      ["Model (as returned by the API)", [...new Set(ex.map((e) => e.model))].sort().map((x) => `\`${x}\``).join(", ")],
      ["Prompt version", [...new Set(ex.map((e) => e.promptVersion ?? "(unrecorded)"))].sort().map((x) => `\`${x}\``).join(", ")],
      ["Model calls made", times.length ? `${times[0]} to ${times.at(-1)}` : "unrecorded"],
      ["Tokens", `${tokIn.toLocaleString("en-US")} input, ${tokOut.toLocaleString("en-US")} output`],
      ["Latency per contract", med === null ? "n/a" : `median ${(med / 1000).toFixed(1)}s, max ${(Math.max(...ex.map((e) => e.ms)) / 1000).toFixed(1)}s`],
    );
  }
  L.push(...table(["", ""], runRows), "");

  // ── Headline ──────────────────────────────────────────────────────────
  L.push("## Headline", "", "95% intervals are a percentile bootstrap over contracts (2,000 resamples, fixed seed).", "");
  L.push(
    ...table(
      ["Metric", "Value", "95% interval"],
      [
        ["Value accuracy", frac(m.fields - m.wrong, m.fields), ci(bootstrap(results, (x) => x.accuracy))],
        ["Quotes verified in the PDF", frac(quoted.filter((f) => f.quoteVerified).length, quoted.length), ci(bootstrap(results, (x) => x.quoteVerifiedRate))],
        ["Wrong fields", String(m.wrong), ""],
        ["Wrong fields the model itself marked medium or low (calibration)", m.wrong ? frac(misses.filter((f) => f.confidence === "medium" || f.confidence === "low").length, m.wrong) : "n/a", ""],
        ["Silent errors, production policy (L3)", `${m.layers.L3.silentErrors} of ${m.fields} fields (${pct(m.layers.L3.silentRate, 2)})`, ci(bootstrap(results, (x) => x.layers.L3.silentRate))],
        ["Review burden, production policy (L3)", frac(all.filter((f) => f.flagged.L3).length, m.fields), ci(bootstrap(results, (x) => x.layers.L3.burden))],
      ],
    ),
    "",
  );

  // ── Gate ──────────────────────────────────────────────────────────────
  if (opts.thresholds) {
    const gate = evaluateGate(run, opts.thresholds);
    L.push("## Regression gate", "", `Thresholds from \`evals/thresholds.json\`; \`pnpm eval:gate\` exits non-zero when any row fails. Verdict: **${gate.pass ? "pass" : "FAIL"}**.`, "");
    L.push(...table(["Check", "Actual", "Required", ""], gate.checks.map((c) => [c.name, c.actual, c.required, c.pass ? "ok" : "**FAIL**"])), "");
  }

  // ── Ablation ──────────────────────────────────────────────────────────
  L.push("## Review-layer ablation", "", "The same extractions under four review policies, each adding a layer. Silent = wrong and not flagged. Caught = share of wrong fields flagged. Burden = share of all fields flagged.", "");
  L.push(
    ...table(
      ["Policy", "Silent errors", "Silent rate", "Caught", "Caught 95% interval", "Burden"],
      LAYERS.map((l) => {
        const x = m.layers[l];
        return [`${l} ${LAYER_LABEL[l]}`, x.silentErrors, pct(x.silentRate, 2), pct(x.catchRate), ci(bootstrap(results, (y: Metrics) => y.layers[l].catchRate)), pct(x.burden)];
      }),
    ),
    "",
  );
  if (m.wrong) L.push(`The "caught" figures rest on ${m.wrong} wrong field${m.wrong === 1 ? "" : "s"}, which is why their intervals are wide.`, "");

  // ── By category ───────────────────────────────────────────────────────
  L.push("## By category", "");
  L.push(
    ...table(
      ["Category", "Contracts", "Accuracy", "Quotes verified", "Wrong", "Silent L0", "Silent L1", "Silent L2", "Silent L3", "Burden L3"],
      categories.map((c) => {
        const x = metrics(results.filter((r) => r.category === c));
        return [c, x.contracts, frac(x.fields - x.wrong, x.fields), pct(x.quoteVerifiedRate), x.wrong, ...LAYERS.map((l) => x.layers[l].silentErrors), pct(x.layers.L3.burden)];
      }),
    ),
    "",
  );

  // ── By field ──────────────────────────────────────────────────────────
  const fieldRow = (label: string, fs: FieldResult[]) => {
    const t = tally(fs);
    return [label, frac(t.correct, t.n), fs.filter((f) => !absent(f, f.expected)).length, fs.filter((f) => f.quoted).length, frac(t.flagged, t.n), t.wrong, t.silent];
  };
  const fieldHead = ["Accuracy", "Present in key", "Quoted by model", "Flagged L3", "Wrong", "Silent L3"];
  L.push("## By field group", "");
  const groups = [...new Set(RULE_FIELDS.map(groupOf))];
  L.push(...table(["Group", ...fieldHead], groups.map((g) => fieldRow(g, all.filter((f) => groupOf(f.path) === g)))), "");
  L.push("## By field", "", "\"Present in key\" counts contracts whose answer key has a value for the field; the rest expect the model to report it absent.", "");
  L.push(...table(["Field", ...fieldHead], RULE_FIELDS.map((p) => fieldRow(`\`${p}\``, all.filter((f) => f.path === p)))), "");

  // ── Confidence ────────────────────────────────────────────────────────
  L.push("## By model confidence", "", "Error rate within each confidence the model attached to its evidence. \"none\" is a field with no evidence: reported absent, or a value proposed without a quote.", "");
  L.push(
    ...table(
      ["Confidence", "Fields", "Wrong", "Error rate", "Flagged L3"],
      (["high", "medium", "low", null] as const).map((c) => {
        const fs = all.filter((f) => f.confidence === c);
        const t = tally(fs);
        return [c ?? "none", t.n, t.wrong, t.n ? pct(t.wrong / t.n) : "n/a", t.n ? frac(t.flagged, t.n) : "0"];
      }),
    ),
    "",
  );

  // ── Confusion tables ──────────────────────────────────────────────────
  const has = (key: boolean, got: boolean) => all.filter((f) => !absent(f, f.expected) === key && !absent(f, f.actual) === got);
  const both = has(true, true);
  L.push("## Presence confusion", "", "Whether the model reports a value where the answer key has one. A spurious value is a term the contract does not state; a missed value is a term it does.", "");
  L.push(
    ...table(
      ["", "Model gave a value", "Model reported absent"],
      [
        ["Key has a value", `${both.length} (${both.filter((f) => !f.correct).length} with the wrong value)`, `${has(true, false).length} missed`],
        ["Key says absent", `${has(false, true).length} spurious`, `${has(false, false).length}`],
      ],
    ),
    "",
  );
  const classes = ["pay_when_paid", "pay_if_paid", "fixed_days", "silent"];
  const timing = all.filter((f) => f.path === "timing.type");
  const cls = (v: unknown) => (v === null || v === undefined ? "silent" : String(v));
  L.push("## `timing.type` confusion", "", "Rows are the answer key, columns the model. The field with the largest payment consequence: it decides whether the contractor owes the subcontractor when the owner does not pay.", "");
  L.push(...table(["Key \\ Model", ...classes], classes.map((e) => [e, ...classes.map((a) => timing.filter((f) => cls(f.expected) === e && cls(f.actual) === a).length)])), "");

  // ── Misses ────────────────────────────────────────────────────────────
  L.push("## Every miss", "");
  if (!misses.length) L.push("None.", "");
  else {
    L.push(
      ...table(
        ["Contract", "Category", "Field", "Error type", "Expected", "Got", "Model confidence", "L1", "L2", "L3 (production)"],
        misses.map((f) => [f.slug, f.category, `\`${f.path}\``, f.kind, cell(f.expected), cell(f.actual), f.confidence ?? "none", ...(["L1", "L2", "L3"] as const).map((l) => (f.flagged[l] ? "flagged" : "**silent**"))]),
      ),
      "",
    );
  }

  // ── Per contract ──────────────────────────────────────────────────────
  L.push("## Per contract", "");
  L.push(
    ...table(
      ["Contract", "Category", "Correct", "Flagged L3", "Silent L3", "Wrong fields"],
      results.map((r) => {
        const t = tally(r.fields);
        return [r.slug, r.category, `${t.correct}/${t.n}`, t.flagged, t.silent, r.fields.filter((f) => !f.correct).map((f) => `\`${f.path}\``).join(", ") || ""];
      }),
    ),
  );
  return L.join("\n") + "\n";
}
